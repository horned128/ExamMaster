def split_choices(chunk):
    groups=list(re.finditer(r'解答群',chunk))
    if groups:
        pos=groups[-1].end()
    else:
        # A-subject options usually start with the first line beginning in ア.
        m=re.search(r'(?m)^\s*ア\s+',chunk)
        if not m: return chunk.strip(),[]
        pos=m.start()
    search=chunk[pos:]
    raw=list(LABEL.finditer(search))
    if not raw: return chunk.strip(),[]
    # A label must begin a choice group and labels are contiguous from ア.
    selected=[]
    seen=set()
    for m in raw:
        label=m.group(1)
        idx=KANA.index(label)
        if label in seen: continue
        seen.add(label)
        selected.append((idx,m.start(1),m.end(),label))
    indices=sorted(x[0] for x in selected)
    if not indices or indices!=list(range(indices[-1]+1)):
        return chunk.strip(),[]
    by_label={}
    ordered=sorted(selected)
    for i,(idx,a,b,label) in enumerate(selected):
        next_positions=[x[1] for x in selected if x[1]>a]
        end=min(next_positions) if next_positions else len(search)
        value=search[b:end].strip()
        value=re.sub(r'試験問題に記載されている会社名又は製品名[\s\S]*$', '', value).strip()
        value=re.sub(r'\s+',' ',value)
        value=re.sub(r'\s*\n\s*',' ',value)
        if value: by_label[label]=value
    options=[(label,by_label[label]) for _,_,_,label in ordered if label in by_label]
    stem=chunk[:pos].strip()
    stem=re.sub(r'(?:解答群)\s*$','',stem).strip()
    return stem,options


def format_code(text):
    """Restore readable indentation for PDFKit's flattened pseudo-code lines."""
    lines=[re.sub(r'[ \t]+',' ',line).strip() for line in text.splitlines()]
    out=[]; depth=0
    dedent=re.compile(r'^(?:endif|endwhile|endfor|until\b|else\b|elseif\b)')
    indent_after=re.compile(r'^(?:if\b|while\b|for\b|do\b|else\b|elseif\b)')
    for line in lines:
        if not line: out.append(''); continue
        if dedent.match(line): depth=max(0,depth-1)
        out.append(('    '*depth)+line)
        if indent_after.match(line): depth+=1
        if line.startswith('○'): depth=0
    return '\n'.join(out)


