def question(s, q, category, stem, code, answer, trace, explanation, choices, wrongs, tags):
    # answer and alternatives are rendered as distinct strings; correctness is easy to audit.
    ordered=[answer]+choices[:3]
    shift=(s*7+q*3)%4
    ordered=ordered[shift:]+ordered[:shift]
    ci=ordered.index(answer)
    ex=[]
    for c in ordered:
        ex.append(explanation if c==answer else wrongs[choices.index(c)])
    context,pseudocode=split_context_code(code)
    blocks=[]
    if context: blocks.append({'type':'text','text':context})
    if pseudocode: blocks.append({'type':'monospace','text':pseudocode})
    blocks.append({'type':'text','text':stem})
    return {'id':f'fe-practice-b-{s+1:02}-q{q:02}','year':2026,'subject':'科目B','category':category,'stem':stem,
      'choices':ordered,'correctIndex':ci,'explanation':explanation,'source':f'ピヨトレ！オリジナル 科目B 第{s+1}回 問{q}',
      'questionNumber':q,'difficulty':2+(q%3),'tags':tags,'concepts':tags,'administration':f'practice-b-{s+1:02}',
      'kind':'original','mockSetID':f'fe-practice-b-{s+1:02}','bodyBlocks':blocks,
      'explanationBlocks':[{'type':'text','text':explanation},{'type':'table','headers':trace[0],'rows':trace[1:] or [['—']*len(trace[0])]}],
      'choiceExplanations':ex,
      'steps':[f'擬似コードを要素番号1始まりで初期化から順に追跡する。',explanation,'境界を確認する。配列参照と繰返し回数は設問で与えた範囲内で、再帰またはループは必ず終了する。']}

def split_context_code(prompt):
    markers=['関数 区間和','Sの各文字 c','Qが空でない間','i を 2 から','下限位置(A','整数型: 計算','整数型: gcd','主 ← 0; 副 ← 0','x ← ','位置 ← (k mod','対象 ← 先頭','i を 1 から','配列 dp は','while i ≤ length(S)','関数 転倒数','転倒数 ← 0','i ← 1; j ← 1','左 ← 1; 右 ←','各トークン t']
    hits=[prompt.find(m) for m in markers if prompt.find(m)>=0]
    if not hits: return prompt,''
    start=min(hits); return prompt[:start].strip(),prompt[start:].strip()

