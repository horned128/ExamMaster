def reference_result(k,s):
    """Second implementation for arithmetic and traversal checks; intentionally independent of compute()."""
    n=s+1
    if k=='sum': return sum([n+2,2*n+1,n+4,3*n-1,n+6,2*n+3][1:5])
    if k=='depth':
        seq=['(()())','(()(()))','()(())()','((())())','()(()())','((()))()','(()())()','()(())(())','((()()))','()((()))','(()(()))()','((())(()))'][s]
        level=best=0
        for c in seq: level += (1 if c=='(' else -1); best=max(best,level)
        return best
    if k=='round':
        rem=[n+1,2,n+3,1]; finish=[]; turn=0
        while any(rem):
            i=turn%4
            if rem[i]:
                rem[i]=max(0,rem[i]-2)
                if rem[i]==0: finish.append(i+1)
            turn+=1
        return finish[-1]
    if k=='insert':
        arr=[7+n,3+n,5+n,2*n+1,4+n]; count=0
        for i in range(1,len(arr)):
            x=arr[i]
            count += sum(1 for j in range(i) if arr[j]>x)
        return count
    if k=='lower':
        arr=sorted([1+n,4+n,4+n,8+n,12+n,15+n]); x=4+n
        return next((i+1 for i,v in enumerate(arr) if v>=x),len(arr)+1)
    if k=='recur': return sum(2*x for x in range(2,4+n+1))
    if k=='gcd': return gcd(42+3*n,18+2*n)
    if k=='matrix':
        arr=[[n,2,1],[3,n+1,4],[2,5,n+2]]
        return sum(arr[i][i]-arr[i][2-i] for i in range(3))
    if k=='rle':
        chars=['A','B','A','A','C','C','C','A','B','B','A','A','A','C']; chars=chars[s%3:]+chars[:s%3]
        return ''.join(ch+str(len(list(g))) for ch,g in groupby(chars))
    if k=='bfs':
        graphs=[[[2,3],[4],[4,5],[6],[6],[6]],[[2,4],[3],[5],[3,5],[6],[6]],[[2,3],[4,5],[5],[6],[6],[6]],[[2,5],[3,4],[6],[6],[4,6],[6]],[[2,3],[4],[4,5],[5,6],[6],[6]],[[2,4],[3,5],[6],[5],[6],[6]],[[2,3],[4,6],[5],[5],[6],[6]],[[2,4],[3,5],[4,6],[6],[6],[6]],[[2,3],[4,5],[6],[6],[5,6],[6]],[[2,5],[3,4],[4,6],[6],[6],[6]],[[2,3],[4],[5,6],[6],[6],[6]],[[2,4],[3,5],[5,6],[6],[6],[6]]]
        d=[-1]*6; d[0]=0; q=deque([0])
        while q:
            u=q.popleft()
            for v in graphs[s][u]:
                if d[v-1]<0: d[v-1]=d[u]+1; q.append(v-1)
        return d[-1]
    if k=='base':
        value=93+17*n; base=2+s%3; digs='0123456789'; out=''
        while value: out=digs[value%base]+out; value//=base
        return out
    if k=='hash':
        slots=[None]*7
        for value in [10+n,18+n,25+n,32+n]:
            pos=value%7
            while slots[pos] is not None: pos=(pos+1)%7
            slots[pos]=value
        return slots.index(32+n)+1
    if k=='list':
        arr=list('ABCDEFG'); del arr[2+s%3]; return ''.join(arr)
    if k=='window':
        arr=[3+n,1,6+n,2,5,4+n,2*n]
        return max(sum(arr[i:i+3]) for i in range(5))
    if k=='inversion':
        arr=[5+n,2+n,7,1+n,4,3+n]
        return sum(1 for i in range(6) for j in range(i+1,6) if arr[i]>arr[j])
    if k=='coin':
        amount=8+s%5; dp=[0]+[999]*(amount)
        for v in range(1,amount+1): dp[v]=1+min(dp[v-c] for c in (1,3,4) if c<=v)
        return dp[amount]
    if k=='merge':
        a=sorted([n+1,n+5,n+8]); b=sorted([n+2,n+4,n+9]); return '、'.join(map(str,sorted(a+b)))
    if k=='palindrome':
        words=['level','radar','refer','kayak','rotor','civic','madam','noon','deed','racecar','redder','tenet']
        w=words[s]; return '回文' if w==w[::-1] else '回文でない'
    if k=='selection': return 4+3+2+1
    if k=='postfix': return 14-(s+1)
    raise ValueError(k)

def make_security(s,q):
    title,case,good,bad1,bad2,bad3,why=SECURITY_CASES[s*4+(q-17)]
    choices=[good,bad1,bad2,bad3]; shift=(s+q)%4; choices=choices[shift:]+choices[:shift]; ci=choices.index(good)
    lead=case.split('。',1)[0]
    stem=f"{title}の事例: {lead}。この状況で最も適切な対応を選ぶ。"
    context=f"【{title}】\n{case}\n\n【業務環境】\n{BUSINESS_CONTEXTS[s]}"
    wrong_reason={bad1:'この案では、設問の脅威・依存条件を残したまま運用を続けてしまう。',bad2:'この案は、必要な記録や承認を欠き、影響範囲を適切に管理できない。',bad3:'この案は、目の前の業務だけを優先し、設問で求める安全性または継続性を損なう。'}
    explanations=[why if c==good else wrong_reason[c] for c in choices]
    steps=['設問で示された資産、脅威、期限、業務制約を対応付ける。','候補ごとに残るリスクと必要な承認・記録を比較する。',why]
    return {'id':f'fe-practice-b-{s+1:02}-q{q:02}','year':2026,'subject':'科目B','category':'情報セキュリティ／'+title,'stem':stem,'choices':choices,'correctIndex':ci,
      'explanation':why,'source':f'ピヨトレ！オリジナル 科目B 第{s+1}回 問{q}','questionNumber':q,'difficulty':3,'tags':[title,'情報セキュリティ'],'concepts':[title],
      'administration':f'practice-b-{s+1:02}','kind':'original','mockSetID':f'fe-practice-b-{s+1:02}',
      'bodyBlocks':[{'type':'text','text':context},{'type':'text','text':stem}], 'choiceExplanations':explanations,'steps':steps}

def build():
    qs=[]; sets=[]
    for s in range(12):
        ids=[]
        for q in range(1,21):
            item=make_algo(s,q) if q<=16 else make_security(s,q)
