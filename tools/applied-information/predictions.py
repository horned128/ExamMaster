def build_sets():
    questions, sets = [], []
    for s in range(1,4):
        rows = concept_questions(s) + calculation_questions(s)
        rows.sort(key=lambda q: [TECH, MANAGEMENT, STRATEGY].index(q["subject"]))
        assert Counter(x["subject"] for x in rows) == {TECH:50, MANAGEMENT:10, STRATEGY:20}
        set_id = f"ap-2026-pred-{s:02d}"
        for n, row in enumerate(rows,1):
            row.update(id=f"{set_id}-q{n:02d}", year=2026, questionNumber=n, kind="prediction",
                       administration="prediction", mockSetID=set_id,
                       source=f"ピヨトレ！ オリジナル 2026年予想問題 第{s}回 問{n}（IPA非公式）")
        questions.extend(rows)
        sets.append(dict(id=set_id,title=f"2026年予想問題 第{s}回",kind="prediction",
                         questionIDs=[q["id"] for q in rows],questionCount=80,minutes=150))
    assert len(questions)==240 and len({q["stem"] for q in questions})==240
    return questions, sets
