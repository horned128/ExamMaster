def concepts():
    result = []
    for subject, source in [(TECH, TECH_CONCEPTS), (MANAGEMENT, MANAGEMENT_CONCEPTS), (STRATEGY, STRATEGY_CONCEPTS)]:
        for line in source.strip().splitlines():
            parts = line.split("|")
            assert len(parts) == 8, parts
            name, category, scenario, definition, a, b, c, wrong = parts
            result.append(dict(subject=subject, category=category, name=name, scenario=scenario,
                               definition=definition, facts=[a, b, c], wrong=wrong))
    assert Counter(x["subject"] for x in result) == {TECH: 36, MANAGEMENT: 7, STRATEGY: 17}
    return result


